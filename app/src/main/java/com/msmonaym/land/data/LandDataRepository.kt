    fun calculateRegistrationFee(landValue: Double): RegistrationFeeResult {
        val regFee = landValue * 0.01 // 1% Registration Fee
        val stampDuty = landValue * 0.015 // 1.5% Stamp Duty
        val localGovtTax = landValue * 0.02 // 2% Local Govt Tax
        val sourceTax = landValue * 0.02 // 2% AIT / Source Tax
        val total = regFee + stampDuty + localGovtTax + sourceTax
        return RegistrationFeeResult(
            landValue = landValue,
            registrationFee = regFee,
            stampDuty = stampDuty,
            localGovtTax = localGovtTax,
            sourceTax = sourceTax,
            totalFee = total
        )
    }
