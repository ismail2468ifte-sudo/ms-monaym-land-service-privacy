    fun generateDeedText(form: DeedFormData): String {
        return when (form.deedCategory) {
            DeedCategory.SAF_KABALA -> generateSafKabalaText(form)
            DeedCategory.FLAT_BAYNAMA -> generateFlatBaynamaText(form)
            DeedCategory.FLAT_SAF_KABALA -> generateFlatSafKabalaText(form)
            DeedCategory.HEBA_DANPATRO -> generateHebaDanpatroText(form)
            DeedCategory.HEBA_BIL_EWAZ -> generateHebaBilEwazText(form)
            DeedCategory.BAYNAMA -> generateBaynamaText(form)
            DeedCategory.PARTITION_BONTAN -> generatePartitionBontanText(form)
            DeedCategory.POWER_OF_ATTORNEY -> generatePowerOfAttorneyText(form)
            DeedCategory.EXCHANGE_EWAZ -> generateExchangeEwazText(form)
            DeedCategory.RELINQUISHMENT_NADABI -> generateRelinquishmentNadabiText(form)
            DeedCategory.WILL_OCHIYOT -> generateWillOchiyotText(form)
            DeedCategory.MORTGAGE_BONDHOK -> generateMortgageBondhokText(form)
        }
    }

